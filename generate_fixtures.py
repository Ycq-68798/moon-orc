from pathlib import Path
import pyarrow as pa
import pyarrow.orc as orc

root = Path(__file__).parent
values = [0, -1, 7, None, -128, 127, 22, -35, None, 4, 5, 6, 7, 8, 9]
table = pa.table({
  'tiny': pa.array(values, type=pa.int8()),
  'small': pa.array(values, type=pa.int16()),
  'big': pa.array([0, -1, 2**40, None, -(2**40), 2**63-1, -(2**63), 42, None, 1, 2, 3, 4, 5, 6], type=pa.int64()),
  'empty': pa.array([None] * len(values), type=pa.int32()),
})

def encode(compression, version):
    sink = pa.BufferOutputStream()
    orc.write_table(table, sink, compression=compression, file_version=version)
    data = sink.getvalue().to_pybytes()
    decoded = orc.read_table(pa.BufferReader(data))
    assert decoded.equals(table)
    return data

def literal(data):
    return '[' + ', '.join(f'0x{b:02x}' for b in data) + ']'

def expected(values):
    return '[' + ', '.join('None' if v is None else f'Some({v}L)' for v in values) + ']'

v11 = encode('uncompressed', '0.11')
v12 = encode('uncompressed', '0.12')
zlib = encode('zlib', '0.11')
multi_values = [i % 11 - 5 if i % 7 else None for i in range(5000)]
multi_table = pa.table({'x': pa.array(multi_values, type=pa.int32())})
multi_sink = pa.BufferOutputStream()
orc.write_table(multi_table, multi_sink, compression='uncompressed', file_version='0.11', stripe_size=128, batch_size=256)
multi = multi_sink.getvalue().to_pybytes()
assert orc.read_table(pa.BufferReader(multi)).equals(multi_table)
assert orc.ORCFile(pa.BufferReader(multi)).nstripes > 1
output = '''// Generated by generate_fixtures.py using Apache Arrow; do not hand-edit.\n///|\n'''
for name, data in [('fixture_11', v11), ('fixture_12', v12), ('fixture_zlib', zlib), ('fixture_multi', multi)]:
    output += f'fn {name}() -> Bytes {{\n  {literal(data)}\n}}\n\n///|\n'
output += '''test "Apache Arrow ORC 0.11 integer interoperability" {\n  let file = open(fixture_11())\n  assert_eq(file.rows, 15)\n  assert_eq(file.stripes.length(), 1)\n  assert_eq(file.types[0].names, ["tiny", "small", "big", "empty"])\n'''
for col in table.column_names:
    output += f'  assert_eq(file.read_int_column("{col}"), {expected(table[col].to_pylist())})\n'
output += '''}\n\n///|\ntest "Apache Arrow ORC 0.12 byte interoperability and unsupported encoding" {\n  let file = open(fixture_12())\n'''
output += f'  assert_eq(file.read_int_column("tiny"), {expected(values)})\n'
output += '''  let unsupported = try file.read_int_column("small") catch { Invalid(_) => true } noraise { _ => false }\n  assert_true(unsupported)\n}\n\n///|\ntest "reject invalid and compressed files" {\n  let bad = try open(b"bad") catch { Invalid(_) => true } noraise { _ => false }\n  let compressed = try open(fixture_zlib()) catch { Invalid(_) => true } noraise { _ => false }\n  assert_true(bad)\n  assert_true(compressed)\n}\n'''
output += '''
///|
test "Apache Arrow multi-stripe projection" {
  let file = open(fixture_multi())
  assert_eq(file.rows, 5000)
  assert_true(file.stripes.length() > 1)
  let result = file.read_int_column("x")
  for i in 0..<5000 {
    let expected = if i % 7 == 0 { None } else { Some(Int64::from_int(i % 11 - 5)) }
    assert_eq(result[i], expected)
  }
}
'''
(root / 'interop_wbtest.mbt').write_text(output, encoding='utf-8')
(root / 'sample.orc').write_bytes(v11)
print(f'Arrow {pa.__version__}: fixture sizes v0.11={len(v11)}, v0.12={len(v12)}, zlib={len(zlib)}')
